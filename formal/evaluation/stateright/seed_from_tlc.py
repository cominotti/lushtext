"""E3: turn a TLC counterexample of formal/evaluation/tlaplus/Journal.tla into
a Rust regression test that replays it against the real journal_core through
src/env.rs. Disposable evaluation tooling.

usage: seed_from_tlc.py TLC_OUTPUT TEST_NAME EXPECTED_BROKEN > tests/<file>.rs
EXPECTED_BROKEN is one of: s1, body_without_entry, cleanup_unsafe.
"""
import re
import sys

text = open(sys.argv[1]).read()
name, broken = sys.argv[2], sys.argv[3]
states = re.split(r"\nState \d+: ", text)[1:]
if not states:
    sys.exit("no trace in the TLC output")


def field(block, key, function=False):
    """The TLA+ value of `key |-> ...` in a pretty-printed record; with
    `function`, only a field whose value is a TLA+ function `( ... )`."""
    m = re.search(r"\b%s \|->\s*%s" % (key, r"(?=\()" if function else ""), block)
    if not m:
        return None
    i, depth, out = m.end(), 0, []
    while i < len(block):
        c = block[i]
        # `:>`, `|->`, and `@@` contain angle brackets, so only ( [ { nest.
        if c in "([{":
            depth += 1
        elif c in ")]}":
            if depth == 0:
                break
            depth -= 1
        elif c == "," and depth == 0:
            break
        out.append(c)
        i += 1
    return " ".join("".join(out).split())


first = states[0]
entry = dict(re.findall(r"(\d) :> \[present \|-> (TRUE|FALSE)", field(first, "entry", True)))
body = dict(re.findall(r"(\d) :> (-?\d+)", field(first, "body", True)))
backing = dict(re.findall(r"(\d) :> (\d+)", field(first, "backing", True)))
preserved = set(re.findall(r"\d+", field(first, "preserved") or ""))
ids = sorted(entry)
# The first TLC state is after the startup(s): a body the startup set aside
# (no entry) is gone from `body` and its content (1 + id) is in `preserved`.
previous = []
for i in ids:
    had_body = body[i] != "-1" or str(1 + int(i)) in preserved
    previous.append((entry[i] == "TRUE", had_body, backing[i] != "0"))

steps = []
for block in states[1:]:
    m = re.search(r"/\\ last = (\[.*?\])\s*(?:\n/\\|\n\n|\Z)", block, re.S)
    if m is None:
        continue
    last = " ".join(m.group(1).split())
    d = dict(re.findall(r'(\w+) \|-> ("?[\w-]+"?)', last))
    action = d["act"].strip('"')
    ending = d["ending"].strip('"')
    steps.append((d["actorB"] == "TRUE", action, int(d["id"]), d["fault"] == "TRUE",
                  None if ending == "-" else ending))

action_names = {"DeletionStep": "DeletionStep"}
out = []
out.append("// SPDX-License-Identifier: GPL-3.0-or-later")
out.append("// Generated by seed_from_tlc.py from a TLC counterexample of Journal.tla (E3).")
out.append("#[allow(unused_imports)]")
out.append("use lushtext_core::services::draft_service::journal_core::RestoreEnding;")
out.append("use lushtext_journal_stateright::env::{Action, Journal, PreviousId};")
out.append("")
out.append("#[test]")
out.append("fn %s() {" % name)
out.append("    let previous = [")
for e, b, m in previous:
    out.append("        PreviousId { entry: %s, body: %s, backing_moved: %s }," % (str(e).lower(), str(b).lower(), str(m).lower()))
out.append("    ];")
out.append("    let mut journal = Journal::previous_session(previous).with_second_process();")
out.append("    journal.step_as(false, Action::Startup, 0, false, None);")
out.append("    journal.step_as(true, Action::Startup, 0, false, None);")
for actor, action, i, fault, ending in steps:
    rust_ending = "None" if ending is None else "Some(RestoreEnding::%s)" % ending
    out.append("    journal.step_as(%s, Action::%s, %d, %s, %s);" % (
        str(actor).lower(), action_names.get(action, action), i, str(fault).lower(), rust_ending))
check = {"s1": "!journal.acceptance_durability_holds()",
         "body_without_entry": "journal.body_without_entry",
         "cleanup_unsafe": "journal.cleanup_unsafe"}[broken]
out.append("    assert!(%s, \"the TLC counterexample reproduces on the real journal_core\");" % check)
out.append("}")
print("\n".join(out))
