"""E2: turn recorded workflow-events.json smoke artifacts into a TLC trace-
validation model and a set of Quint `run` tests. Reads artifacts only.

usage: gen_traces.py OUT_DIR [--mutate] ARTIFACT...
--mutate swaps the phases of the first two events of the first non-empty
trace, to show that validation rejects a corrupted log.
"""
import json, os, sys

def main():
    out = sys.argv[1]; mutate = "--mutate" in sys.argv
    files = [a for a in sys.argv[2:] if a != "--mutate"]
    traces = []
    for f in sorted(files):
        ev = json.load(open(f)).get("events", [])
        if ev:
            traces.append((f, ev))
    if mutate:
        ev = traces[0][1]
        ev[0]["phase"], ev[1]["phase"] = ev[1]["phase"], ev[0]["phase"]
    def tla_ev(e):
        b = e["blocker"] if e["blocker"] is not None else "none"
        return ('[workflow_id |-> "%s", phase |-> "%s", status |-> "%s", blocker |-> "%s", sequence |-> %d]'
                % (e["workflow_id"], e["phase"], e["status"], b, e["sequence"]))
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, "WorkflowEventsTraces.tla"), "w") as t:
        t.write("---- MODULE WorkflowEventsTraces ----\n(* Generated by gen_traces.py; do not edit. *)\n")
        t.write("Traces == <<\n" + ",\n".join(
            "  (* %s *) <<%s>>" % (f.split("build/smoke/")[-1], ", ".join(tla_ev(e) for e in ev))
            for f, ev in traces) + "\n>>\n====\n")
    def q_ev(e):
        b = e["blocker"] if e["blocker"] is not None else "none"
        return ('{ workflowId: "%s", phase: "%s", status: "%s", blocker: "%s", sequence: %d }'
                % (e["workflow_id"], e["phase"], e["status"], b, e["sequence"]))
    with open(os.path.join(out, "workflow_events_traces.qnt"), "w") as q:
        q.write("// Generated by gen_traces.py; do not edit.\nmodule workflow_events_traces {\n")
        # Quint resolves `from` relative to the importing file, and rejects absolute paths.
        spec = os.path.join(os.path.dirname(os.path.abspath(__file__)), "workflow_events")
        q.write('  import workflow_events.* from "%s"\n' % os.path.relpath(spec, os.path.abspath(out)))
        for k, (f, ev) in enumerate(traces):
            q.write("  // %s\n  run trace%dTest = init" % (f.split("build/smoke/")[-1], k))
            for e in ev:
                q.write("\n    .then(emit(%s))" % q_ev(e))
            q.write("\n")
        q.write("}\n")
    print(len(traces), "traces,", sum(len(ev) for _, ev in traces), "events")

main()
