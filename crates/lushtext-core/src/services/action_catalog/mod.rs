/// Result type used by catalog checks that may report several drift findings.
pub type AuditResult = Result<(), Vec<ActionCatalogAuditFailure>>;

/// One actionable catalog drift finding.
#[derive(Clone, Debug, Eq, PartialEq)]
pub enum ActionCatalogAuditFailure {
    DuplicateActionIds(Vec<String>),
    MissingDocsAnchors(Vec<String>),
    MissingCoverage(Vec<String>),
    MissingCatalogEntries {
        source: &'static str,
        action_ids: Vec<String>,
    },
    MissingRegisteredActions {
        scope: ActionScope,
        action_ids: Vec<String>,
    },
    TypeMismatches(Vec<ActionSignatureMismatch>),
}

/// Expected-versus-observed type mismatch for one exported action.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct ActionSignatureMismatch {
    pub action_id: String,
    pub expected_parameter: ActionValueType,
    pub observed_parameter: ActionValueType,
    pub expected_state: ActionValueType,
    pub observed_state: ActionValueType,
}

/// Return the complete catalog for the current implementation baseline.
#[must_use]
pub fn entries() -> &'static [ActionCatalogEntry] {
    ACTION_CATALOG
}

/// Generate the serializable artifact consumed by developer automation docs.
#[must_use]
pub fn developer_reference_rows() -> Vec<ActionReferenceRow> {
    ACTION_CATALOG
        .iter()
        .map(ActionReferenceRow::from)
        .collect()
}

/// Generate pretty JSON for docs tooling without hand-copying catalog fields.
///
/// # Errors
///
/// Returns a serialization error if the catalog contains a value that serde
/// cannot encode. The current catalog is static and should not fail.
pub fn developer_reference_json() -> serde_json::Result<String> {
    serde_json::to_string_pretty(&developer_reference_rows())
}

/// Check catalog-only invariants before comparing against external surfaces.
///
/// # Errors
///
/// Returns every catalog invariant violation found, such as duplicate action
/// IDs, missing documentation anchors, or rows without coverage lanes.
pub fn audit_catalog(entries: &[ActionCatalogEntry]) -> AuditResult {
    let mut failures = Vec::new();
    let mut seen = BTreeSet::new();
    let mut duplicates = BTreeSet::new();
    let mut missing_docs = Vec::new();
    let mut missing_coverage = Vec::new();

    for entry in entries {
        let action_id = entry.qualified_id();
        if !seen.insert(action_id.clone()) {
            duplicates.insert(action_id.clone());
        }
        if entry.docs_anchor.trim().is_empty() {
            missing_docs.push(action_id.clone());
        }
        if entry.coverage_lanes.is_empty() {
            missing_coverage.push(action_id);
        }
    }

    if !duplicates.is_empty() {
        failures.push(ActionCatalogAuditFailure::DuplicateActionIds(
            duplicates.into_iter().collect(),
        ));
    }
    if !missing_docs.is_empty() {
        failures.push(ActionCatalogAuditFailure::MissingDocsAnchors(missing_docs));
    }
    if !missing_coverage.is_empty() {
        failures.push(ActionCatalogAuditFailure::MissingCoverage(missing_coverage));
    }

    finish_audit(failures)
}

/// Compare observed app/window action signatures against exported catalog rows.
///
/// # Errors
///
/// Returns drift findings when exported actions are missing from the catalog,
/// cataloged exports are not registered, or observed parameter/state types no
/// longer match their catalog rows.
pub fn audit_observed_actions(scope: ActionScope, observed: &[ObservedAction<'_>]) -> AuditResult {
    let expected = exported_entries_by_name(scope);
    let observed_by_name: BTreeMap<&str, &ObservedAction> = observed
        .iter()
        .filter(|action| action.scope == scope)
        .map(|action| (action.name.as_ref(), action))
        .collect();

    let mut failures = Vec::new();
    let mut missing_catalog = Vec::new();
    let mut missing_registered = Vec::new();
    let mut mismatches = Vec::new();

    for observed_action in observed_by_name.values() {
        let Some(expected_entry) = expected.get(observed_action.name.as_ref()) else {
            missing_catalog.push(observed_action.qualified_id());
            continue;
        };
        if expected_entry.parameter_type != observed_action.parameter_type
            || expected_entry.state_type != observed_action.state_type
        {
            mismatches.push(ActionSignatureMismatch {
                action_id: observed_action.qualified_id(),
                expected_parameter: expected_entry.parameter_type,
                observed_parameter: observed_action.parameter_type,
                expected_state: expected_entry.state_type,
                observed_state: observed_action.state_type,
            });
        }
    }

    for expected_name in expected.keys() {
        if !observed_by_name.contains_key(expected_name) {
            missing_registered.push(scope.qualified_id(expected_name));
        }
    }

    if !missing_catalog.is_empty() {
        failures.push(ActionCatalogAuditFailure::MissingCatalogEntries {
            source: "registered-actions",
            action_ids: missing_catalog,
        });
    }
    if !missing_registered.is_empty() {
        failures.push(ActionCatalogAuditFailure::MissingRegisteredActions {
            scope,
            action_ids: missing_registered,
        });
    }
    if !mismatches.is_empty() {
        failures.push(ActionCatalogAuditFailure::TypeMismatches(mismatches));
    }

    finish_audit(failures)
}

/// Check command-palette command IDs against the shared catalog.
///
/// # Errors
///
/// Returns missing-catalog findings when a command-palette entry references an
/// action ID that is not represented in the shared catalog.
pub fn audit_command_palette_actions() -> AuditResult {
    audit_cataloged_ids(
        "command-palette",
        palette::all_commands().iter().map(|command| command.id),
    )
}

/// Check statically discoverable menu, shortcut, toolbar, and context actions.
///
/// # Errors
///
/// Returns missing-catalog findings when a statically discoverable menu,
/// shortcut, toolbar, or context-menu action has no shared catalog row.
pub fn audit_visible_static_actions() -> AuditResult {
    audit_cataloged_ids(
        "visible-static-actions",
        STATIC_VISIBLE_ACTION_IDS.iter().copied(),
    )
}

fn audit_cataloged_ids(
    source: &'static str,
    ids: impl IntoIterator<Item = &'static str>,
) -> AuditResult {
    let cataloged: BTreeSet<String> = ACTION_CATALOG
        .iter()
        .map(ActionCatalogEntry::qualified_id)
        .collect();
    let mut missing = BTreeSet::new();

    for id in ids {
        if !cataloged.contains(id) {
            missing.insert(id.to_string());
        }
    }

    if missing.is_empty() {
        Ok(())
    } else {
        Err(vec![ActionCatalogAuditFailure::MissingCatalogEntries {
            source,
            action_ids: missing.into_iter().collect(),
        }])
    }
}

fn exported_entries_by_name(
    scope: ActionScope,
) -> BTreeMap<&'static str, &'static ActionCatalogEntry> {
    ACTION_CATALOG
        .iter()
        .filter(|entry| entry.scope == scope && entry.exposure == ActionExposure::Exported)
        .map(|entry| (entry.name, entry))
        .collect()
}

fn finish_audit(failures: Vec<ActionCatalogAuditFailure>) -> AuditResult {
    if failures.is_empty() {
        Ok(())
    } else {
        Err(failures)
    }
}

