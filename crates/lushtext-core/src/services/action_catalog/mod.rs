//! Checked action catalog for automation, documentation, and drift audits.
//!
//! This service layer keeps catalog construction GTK-free while comparing the
//! pure catalog against command registries, visible action strings, and D-Bus
//! introspection snapshots supplied by UI or smoke adapters.

