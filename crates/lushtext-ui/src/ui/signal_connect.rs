//! The one way production code connects to, or emits, a GObject signal by
//! **name**: the handler's return type is checked against the signal's
//! declared return type when the handler is connected (or before the signal
//! is emitted), not inside the emission.
//!
//! **Cross-cutting, no role.** Every string-named connection or emission in
//! `lushtext-ui` goes through it: the buffer handlers of the edit lock, the
//! paragraph wrap gate and frame validation, and the document scale watch
//! (`WFR-DOCUMENT-SCALE`); held typing's view `backspace` and frame
//! validation's frame-clock `layout`; the load and minimap watches
//! (`WFR-DOCUMENT-LOAD`, `WFR-MINIMAP`); Protected View's interaction and
//! capture handlers (`WFR-PROTECTED-VIEW`); folded-text copies; the command
//! palette and notes browser row objects' `content-changed`
//! (`WFR-COMMAND-PALETTE`, `WFR-NOTES-BOOKMARKS`); and the smoke-only
//! responsiveness probe.
//!
//! Why it exists: glib-rs `ObjectExt::connect_local` takes a closure that
//! returns `Option<glib::Value>` and checks that answer only when the signal
//! is emitted, inside GLib's C marshaller, where a Rust panic cannot unwind:
//! the process aborts. A handler on `GtkTextView::extend-selection` (which
//! returns `gboolean`) answered `None` outside Protected View, and a double
//! click in any ordinary document aborted LushText
//! (`required return value of type 'gboolean' but got None`). Here the
//! handler's Rust type says what it returns, and a mismatch with the declared
//! type panics at the connection, which happens at page, buffer or row
//! construction: any test that builds the surface fails deterministically
//! instead of a user's session aborting on the first emission. The check runs
//! in every build; it is one signal lookup per connection.
//!
//! - [`connect_void`]: the handler returns `()` (or `Option<()>`, so it can
//!   bail out with `?`); the signal must return nothing (`G_TYPE_NONE`).
//! - [`connect_returning`]: the handler returns `R`; the signal must declare
//!   a return type `R` is (`R::static_type().is_a(declared)`), so the value
//!   is always present.
//! - [`emit_void`] and [`emit_returning`]: the same check before an emission
//!   by name.
//!
//! Names may be detailed (`notify::enabled`); the detail is parsed as GLib
//! parses it. Typed `connect_*` methods generated by gtk-rs need none of
//! this: their closure signatures already carry the return type.
//! `make check-signal-connections` forbids `connect`, `connect_local`,
//! `connect_closure`, `connect_unsafe` (and their `_id` forms) and the
//! `emit_by_name` family anywhere in `crates/lushtext-ui/src` outside this
//! module.

use glib::closure::TryFromClosureReturnValue;
use glib::prelude::*;
use glib::subclass::SignalId;

/// What a handler of a signal that returns nothing may answer: `()`, or
/// `Option<()>` so the handler can stop early with `?`. Neither reaches the
/// emission.
pub(crate) trait NoReturnValue {}

impl NoReturnValue for () {}

impl NoReturnValue for Option<()> {}

/// What a handler, or an emitter, expects the signal to return.
#[derive(Clone, Copy)]
enum ExpectedReturn {
    /// The signal returns nothing.
    Nothing,
    /// A handler hands back a value of this type, which must be a declared
    /// return type (or a subtype of it).
    HandlerValue(glib::Type),
    #[cfg_attr(
        not(any(test, feature = "responsiveness-probes")),
        expect(
            dead_code,
            reason = "only the smoke-only responsiveness probe reads a signal's answer"
        )
    )]
    /// An emitter reads back a value of this type, which the declared return
    /// type must be (or be a subtype of).
    EmitterValue(glib::Type),
}

/// Panic unless `signal` exists on `instance` and declares the return type
/// `expected` needs.
#[track_caller]
fn assert_declared_return(instance: glib::Type, signal: &str, expected: ExpectedReturn) {
    let Some((signal_id, _detail)) = SignalId::parse_name(signal, instance, true) else {
        panic!("signal '{signal}' does not exist on '{instance}'");
    };
    let declared = glib::Type::from(signal_id.query().return_type());
    match expected {
        ExpectedReturn::Nothing => assert!(
            declared == glib::Type::UNIT,
            "signal '{signal}' of '{instance}' returns '{declared}', so a handler or emitter \
             expecting nothing would abort the process inside the emission: use \
             connect_returning or emit_returning with a '{declared}' value"
        ),
        ExpectedReturn::HandlerValue(handler) => assert!(
            declared != glib::Type::UNIT && handler.is_a(declared),
            "signal '{signal}' of '{instance}' returns '{declared}', but the handler returns \
             '{handler}': a mismatched answer aborts the process inside the emission"
        ),
        ExpectedReturn::EmitterValue(emitter) => assert!(
            declared != glib::Type::UNIT && declared.is_a(emitter),
            "signal '{signal}' of '{instance}' returns '{declared}', but the emitter reads \
             '{emitter}'"
        ),
    }
}

/// Connect `handler` to the signal `signal` (which may carry a `::detail`)
/// of `object`, `after` the class handler or before it. The handler returns
/// nothing (see [`NoReturnValue`]), so the signal must declare no return
/// value.
///
/// # Panics
///
/// When `object` has no such signal or the signal returns a value.
#[track_caller]
pub(crate) fn connect_void<O, A, F>(
    object: &O,
    signal: &str,
    after: bool,
    handler: F,
) -> glib::SignalHandlerId
where
    O: IsA<glib::Object>,
    A: NoReturnValue,
    F: Fn(&[glib::Value]) -> A + 'static,
{
    assert_declared_return(object.type_(), signal, ExpectedReturn::Nothing);
    object.connect_local(signal, after, move |values| {
        let _: A = handler(values);
        None
    })
}

/// Connect `handler` to the signal `signal` (which may carry a `::detail`)
/// of `object`, `after` the class handler or before it. Every call of the
/// handler answers an `R`, so the emission always receives a value of a type
/// the signal declares.
///
/// # Panics
///
/// When `object` has no such signal, the signal returns nothing, or `R` is not
/// its declared return type (or a subtype of it).
#[track_caller]
pub(crate) fn connect_returning<O, R, F>(
    object: &O,
    signal: &str,
    after: bool,
    handler: F,
) -> glib::SignalHandlerId
where
    O: IsA<glib::Object>,
    R: ToValue + StaticType,
    F: Fn(&[glib::Value]) -> R + 'static,
{
    assert_declared_return(
        object.type_(),
        signal,
        ExpectedReturn::HandlerValue(R::static_type()),
    );
    object.connect_local(signal, after, move |values| {
        Some(handler(values).to_value())
    })
}

/// Emit the signal `signal` of `object`, which returns nothing, with `args`.
///
/// # Panics
///
/// When `object` has no such signal or the signal returns a value (and, as
/// glib-rs does, when `args` do not match its parameters).
#[track_caller]
pub(crate) fn emit_void<O>(object: &O, signal: &str, args: &[&dyn ToValue])
where
    O: IsA<glib::Object>,
{
    assert_declared_return(object.type_(), signal, ExpectedReturn::Nothing);
    object.emit_by_name::<()>(signal, args);
}

/// Emit the signal `signal` of `object` with `args` and return its answer.
///
/// # Panics
///
/// When `object` has no such signal, the signal returns nothing, or its
/// declared return type is not `R` (or a subtype of it), and, as glib-rs
/// does, when `args` do not match its parameters.
#[cfg_attr(
    not(any(test, feature = "responsiveness-probes")),
    expect(
        dead_code,
        reason = "only the smoke-only responsiveness probe reads a signal's answer"
    )
)]
#[track_caller]
pub(crate) fn emit_returning<O, R>(object: &O, signal: &str, args: &[&dyn ToValue]) -> R
where
    O: IsA<glib::Object>,
    R: TryFromClosureReturnValue,
{
    assert_declared_return(
        object.type_(),
        signal,
        ExpectedReturn::EmitterValue(R::static_type()),
    );
    object.emit_by_name::<R>(signal, args)
}

#[cfg(test)]
mod tests {
    //! GIO types register their signals without a display, so these run in
    //! the unit lane: `GApplication::name-lost` returns `gboolean`,
    //! `GSimpleAction::activate` returns nothing, and `notify` is detailed.

    use super::{connect_returning, connect_void, emit_returning, emit_void};
    use std::cell::Cell;
    use std::rc::Rc;

    fn application() -> gio::Application {
        gio::Application::new(None, gio::ApplicationFlags::NON_UNIQUE)
    }

    fn action() -> gio::SimpleAction {
        gio::SimpleAction::new("probe", None)
    }

    #[test]
    fn a_returning_handler_connects_to_a_boolean_signal_and_answers_it() {
        let application = application();
        let calls = Rc::new(Cell::new(0u32));
        let counter = Rc::clone(&calls);
        connect_returning(&application, "name-lost", false, move |_| {
            counter.set(counter.get() + 1);
            true
        });
        let handled: bool = emit_returning(&application, "name-lost", &[]);
        assert!(handled, "the handler's TRUE reached the emitter");
        assert_eq!(calls.get(), 1);
    }

    #[test]
    #[should_panic(expected = "returns 'gboolean'")]
    fn a_void_handler_on_a_boolean_signal_panics_at_connect() {
        connect_void(&application(), "name-lost", false, |_| {});
    }

    #[test]
    #[should_panic(expected = "but the handler returns 'gint'")]
    fn a_handler_of_the_wrong_type_panics_at_connect() {
        connect_returning(&application(), "name-lost", false, |_| 1i32);
    }

    #[test]
    fn a_void_handler_connects_to_a_void_signal_and_runs() {
        let action = action();
        let calls = Rc::new(Cell::new(0u32));
        let counter = Rc::clone(&calls);
        connect_void(&action, "activate", false, move |_| {
            counter.set(counter.get() + 1);
        });
        emit_void(&action, "activate", &[&None::<glib::Variant>]);
        assert_eq!(calls.get(), 1);
    }

    #[test]
    #[should_panic(expected = "returns 'void'")]
    fn a_returning_handler_on_a_void_signal_panics_at_connect() {
        connect_returning(&action(), "activate", false, |_| true);
    }

    #[test]
    #[should_panic(expected = "returns 'void'")]
    fn reading_a_value_from_a_void_signal_panics_before_emitting() {
        let _: bool = emit_returning(&action(), "activate", &[&None::<glib::Variant>]);
    }

    #[test]
    #[should_panic(expected = "returns 'gboolean'")]
    fn emitting_a_boolean_signal_as_void_panics_before_emitting() {
        emit_void(&application(), "name-lost", &[]);
    }

    #[test]
    fn a_detailed_name_connects_to_that_detail_only() {
        let action = action();
        let calls = Rc::new(Cell::new(0u32));
        let counter = Rc::clone(&calls);
        connect_void(&action, "notify::enabled", false, move |_| {
            counter.set(counter.get() + 1);
        });
        action.set_enabled(false);
        action.set_state_hint(None);
        assert_eq!(calls.get(), 1, "only notify::enabled reached the handler");
    }

    #[test]
    #[should_panic(expected = "returns 'void'")]
    fn a_detailed_void_signal_still_refuses_a_returning_handler() {
        connect_returning(&action(), "notify::enabled", false, |_| true);
    }

    #[test]
    #[should_panic(expected = "does not exist")]
    fn an_unknown_signal_panics_at_connect() {
        connect_void(&action(), "no-such-signal", false, |_| {});
    }
}
