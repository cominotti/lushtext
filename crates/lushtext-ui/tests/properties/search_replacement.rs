//! Property tests for deterministic Replace All text transformation.
//!
//! The property target calls the same pure helper used by the on-disk command
//! path, but it avoids files, locks, and undo persistence so generated cases
//! remain fast and reproducible.

use std::collections::BTreeSet;
use std::ops::Range;
use std::path::PathBuf;

use lushtext_model::workspace::content_search::{
    ContentSearchOptions, Replacement, SearchMatch, SearchMatchId,
};
use lushtext_services::search::content_search::generate_replacement_preview;
use lushtext_services::search::content_search::{
    apply_replacements_to_text_for_property_test,
    apply_replacements_to_text_in_chunks_for_property_test,
    apply_replacements_to_text_reference_for_property_test,
    apply_replacements_to_text_reference_outcome_for_property_test,
};
use proptest::prelude::*;
use sha2::Digest as _;

use crate::support;

/// Maximum generated byte offset used for line replacement ranges.
const MAX_RANGE_OFFSET: usize = support::MAX_TEXT_FRAGMENT_CHARS * 2;

proptest! {
    #![proptest_config(support::property_config())]

    /// Stream-replace-all task 2.2: at every chunk size from 1 to 16 (so with
    /// a seam at every byte offset), the streaming engine produces the
    /// reference builder's text and count, and SHA-256 digests of the source
    /// and of that text, over LF, CRLF, lone CR, multi-byte, empty and
    /// unterminated final lines; a file it does not replace ends with the
    /// reference's outcome.
    #[test]
    fn streaming_engine_matches_the_reference_at_every_chunk_size(
        lines in prop::collection::vec(stream_line(), 1..=support::MAX_VECTOR_LEN),
        crlf in prop::collection::vec(any::<bool>(), support::MAX_VECTOR_LEN),
        raw_replacements in prop::collection::vec(replacement_input(), 0..=support::MAX_VECTOR_LEN),
        trailing_newline in any::<bool>(),
    ) {
        let mut original_text = String::new();
        for (index, line) in lines.iter().enumerate() {
            original_text.push_str(line);
            if index + 1 < lines.len() || trailing_newline {
                original_text.push_str(if crlf[index % crlf.len()] { "\r\n" } else { "\n" });
            }
        }
        let replacements = build_unique_line_replacements(&lines, raw_replacements);
        let reference = apply_replacements_to_text_reference_outcome_for_property_test(
            &original_text,
            &replacements,
        );
        let source_digest: [u8; 32] = sha2::Sha256::digest(original_text.as_bytes()).into();
        let expected = reference.map(|(text, count)| {
            let digest: [u8; 32] = sha2::Sha256::digest(text.as_bytes()).into();
            (text, count, source_digest, digest)
        });
        for chunk_len in 1..=16 {
            let actual = apply_replacements_to_text_in_chunks_for_property_test(
                &original_text,
                &replacements,
                chunk_len,
            );
            prop_assert_eq!(&actual, &expected, "chunk length {}", chunk_len);
        }
    }

    #[test]
    fn replacements_clip_ranges_and_apply_from_later_positions_first(
        lines in prop::collection::vec(support::text_fragment(), 1..=support::MAX_VECTOR_LEN),
        raw_replacements in prop::collection::vec(replacement_input(), 0..=support::MAX_VECTOR_LEN),
        use_crlf in any::<bool>(),
        trailing_newline in any::<bool>(),
    ) {
        let line_ending = if use_crlf { "\r\n" } else { "\n" };
        let mut original_text = lines.join(line_ending);
        if trailing_newline {
            original_text.push_str(line_ending);
        }
        let replacements = build_unique_line_replacements(&lines, raw_replacements);
        let expected = expected_replaced_text(&lines, line_ending, trailing_newline, &replacements);

        let actual = apply_replacements_to_text_for_property_test(&original_text, &replacements);
        let reference = apply_replacements_to_text_reference_for_property_test(
            &original_text,
            &replacements,
        );

        prop_assert_eq!(&actual, &reference);
        prop_assert_eq!(actual, expected);
    }

    #[test]
    fn accepted_literal_preview_applies_like_direct_safe_range_replacement(
        prefix in support::text_fragment(),
        matched in "[a-zA-Z0-9]{1,16}",
        suffix in support::text_fragment(),
        replacement in support::optional_text_fragment(),
    ) {
        let line = format!("{prefix}{matched}{suffix}");
        let range = prefix.len()..prefix.len() + matched.len();
        let search_match = SearchMatch::new(
            PathBuf::from("/tmp/lushtext-preview-property.txt"),
            1,
            &line,
            range.clone(),
        )
        .with_id(SearchMatchId::from_index(0));
        let preview = generate_replacement_preview(
            &[search_match],
            &matched,
            &replacement,
            &ContentSearchOptions::default(),
        );
        let mut expected = line.clone();
        expected.replace_range(range, &replacement);

        prop_assert_eq!(preview.len(), 1);
        prop_assert_eq!(preview[0].replaced_line.as_str(), expected.as_str());
        prop_assert_eq!(
            apply_replacements_to_text_for_property_test(&line, &preview.replacements),
            Some((expected, 1)),
        );
    }

    #[test]
    fn accepted_regex_preview_preserves_capture_expansion_and_apply_semantics(
        first in "[a-z]{1,12}",
        second in "[a-z]{1,12}",
    ) {
        let matched = format!("{first}_{second}");
        let line = format!("prefix {matched} suffix");
        let start = "prefix ".len();
        let search_match = SearchMatch::new(
            PathBuf::from("/tmp/lushtext-regex-preview-property.txt"),
            1,
            &line,
            start..start + matched.len(),
        )
        .with_id(SearchMatchId::from_index(0));
        let preview = generate_replacement_preview(
            &[search_match],
            r"([a-z]+)_([a-z]+)",
            "$2-$1",
            &ContentSearchOptions::new(true, true, false, true, None),
        );
        let expected = format!("prefix {second}-{first} suffix");

        prop_assert_eq!(preview.len(), 1);
        prop_assert_eq!(preview[0].replacement.as_ref(), format!("{second}-{first}"));
        prop_assert_eq!(
            apply_replacements_to_text_for_property_test(&line, &preview.replacements),
            Some((expected, 1)),
        );
    }
}

/// One line for the streaming property: ASCII, a lone `\r` inside the line,
/// multi-byte characters, or empty.
fn stream_line() -> impl Strategy<Value = String> {
    prop_oneof![
        support::text_fragment(),
        "[a-c\r]{0,6}".prop_map(|line| line.trim_end_matches('\r').to_string()),
        "[a\u{e9}\u{4e2d}\u{1f600}]{0,4}",
        Just(String::new()),
    ]
}

/// Generate one raw replacement tuple before binding it to the generated text.
fn replacement_input() -> impl Strategy<Value = (usize, Range<usize>, String)> {
    (
        0usize..=support::MAX_VECTOR_LEN + 2,
        range_input(),
        support::optional_text_fragment(),
    )
}

/// Generate a bounded byte range with ordered endpoints.
fn range_input() -> impl Strategy<Value = Range<usize>> {
    (0usize..=MAX_RANGE_OFFSET, 0usize..=MAX_RANGE_OFFSET)
        .prop_map(|(start, end)| start.min(end)..start.max(end))
}

/// Bind generated replacements to line snapshots, keeping at most one per line.
fn build_unique_line_replacements(
    lines: &[String],
    raw_replacements: Vec<(usize, Range<usize>, String)>,
) -> Vec<Replacement> {
    let mut seen_lines = BTreeSet::new();
    let mut replacements = Vec::new();

    for (line_index, match_range, replacement) in raw_replacements {
        let line_number = u64::try_from(line_index + 1).unwrap_or(u64::MAX);
        if !seen_lines.insert(line_number) {
            continue;
        }
        let original_line = lines
            .get(line_index)
            .cloned()
            .unwrap_or_else(|| "missing generated line".to_string());
        replacements.push(Replacement {
            match_id: lushtext_model::workspace::content_search::SearchMatchId::from_index(
                replacements.len(),
            ),
            path: PathBuf::from("/tmp/lushtext-property-search.txt"),
            line_number,
            original_line: original_line.into(),
            replaced_line: String::new(),
            replacement: replacement.into(),
            match_range,
        });
    }

    replacements
}

/// Independently model the expected text transformation for generated cases.
fn expected_replaced_text(
    lines: &[String],
    line_ending: &str,
    trailing_newline: bool,
    replacements: &[Replacement],
) -> Option<(String, usize)> {
    let mut sorted = replacements.to_vec();
    sorted.sort_by(|a, b| {
        b.line_number
            .cmp(&a.line_number)
            .then(b.match_range.start.cmp(&a.match_range.start))
    });

    let mut expected_lines = lines.to_vec();
    let mut replacement_count = 0usize;
    for replacement in &sorted {
        let Ok(line_idx) = usize::try_from(replacement.line_number.saturating_sub(1)) else {
            continue;
        };
        let line = expected_lines.get_mut(line_idx)?;
        let start = replacement.match_range.start.min(line.len());
        let end = replacement.match_range.end.min(line.len());
        if start <= end {
            line.replace_range(start..end, &replacement.replacement);
            replacement_count += 1;
        }
    }

    if replacement_count == 0 {
        return None;
    }

    let mut content = expected_lines.join(line_ending);
    if trailing_newline {
        content.push_str(line_ending);
    }
    Some((content, replacement_count))
}
